    private void performLogin() {
        String username = jTextField1.getText().trim();
        String password = new String(jPasswordField1.getPassword());

        if (username.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please enter your username.",
                    "Username Required",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            jTextField1.requestFocus();
            return;
        }

        if (password.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please enter your password.",
                    "Password Required",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );
            jPasswordField1.requestFocus();
            return;
        }

        boolean isDefaultAdmin = username.equalsIgnoreCase("admin")
                && (password.equals("admin") || password.equals("admin123") || password.equals("Admin@123"));

        boolean isStrongPassword = password.length() >= 8
                && password.matches(".*[A-Z].*")
                && password.matches(".*[a-z].*")
                && password.matches(".*[0-9].*")
                && password.matches(".*[^a-zA-Z0-9].*");

        if (isDefaultAdmin || isStrongPassword) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Login Successful!\nWelcome back, " + username + "!",
                    "Welcome to PetCare",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

            // Open Dashboard and pass logged-in username
            dashboardform dashboard = new dashboardform(username);
            dashboard.setVisible(true);
            this.dispose();
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Invalid username or password!\n\n"
                    + "Accepted Credentials:\n"
                    + "• Default Admin: Username: admin | Password: admin\n"
                    + "• Or any username with a strong password (at least 8 characters,\n"
                    + "  uppercase, lowercase, number, and special character).",
                    "Login Failed",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
            jPasswordField1.setText("");
            jPasswordField1.requestFocus();
        }
    }

