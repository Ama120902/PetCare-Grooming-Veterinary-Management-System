    private void handleTableRowClick() {
        int row = jTable1.getSelectedRow();
        if (row == -1) return;

        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) jTable1.getModel();
        String petName = String.valueOf(model.getValueAt(row, 1));
        String service = String.valueOf(model.getValueAt(row, 2));
        String dateTime = String.valueOf(model.getValueAt(row, 3));
        String currentStatus = String.valueOf(model.getValueAt(row, 4));

        String[] options = {"Mark Confirmed", "Mark Completed", "Mark Cancelled", "Close"};
        int choice = javax.swing.JOptionPane.showOptionDialog(
                this,
                "Appointment Details:\n"
                + "• Pet: " + petName + "\n"
                + "• Service: " + service + "\n"
                + "• Scheduled Time: " + dateTime + "\n"
                + "• Current Status: " + currentStatus + "\n\n"
                + "Choose an action:",
                "Appointment - " + petName,
                javax.swing.JOptionPane.DEFAULT_OPTION,
                javax.swing.JOptionPane.QUESTION_MESSAGE,
                null,
                options,
                options[0]
        );

        if (choice == 0) {
            model.setValueAt("Confirmed", row, 4);
        } else if (choice == 1) {
            model.setValueAt("Completed", row, 4);
        } else if (choice == 2) {
            model.setValueAt("Cancelled", row, 4);
        }
    }

