    private void setupTableDesign() {
        // Table styling matching modern template
        jTable1.getTableHeader().setFont(new Font("Segoe UI", Font.BOLD, 12));
        jTable1.getTableHeader().setForeground(new java.awt.Color(71, 85, 105));
        jTable1.getTableHeader().setBackground(java.awt.Color.WHITE);
        jTable1.getTableHeader().setOpaque(true);
        jTable1.setRowHeight(40);

        // Column widths
        jTable1.getColumnModel().getColumn(0).setPreferredWidth(40);
        jTable1.getColumnModel().getColumn(1).setPreferredWidth(100);
        jTable1.getColumnModel().getColumn(2).setPreferredWidth(120);
        jTable1.getColumnModel().getColumn(3).setPreferredWidth(150);
        jTable1.getColumnModel().getColumn(4).setPreferredWidth(100);

        // Center align the "No" column
        DefaultTableCellRenderer centerRenderer = new DefaultTableCellRenderer();
        centerRenderer.setHorizontalAlignment(SwingConstants.CENTER);
        jTable1.getColumnModel().getColumn(0).setCellRenderer(centerRenderer);

        // Custom Status badge renderer (Green for Confirmed, Amber for Pending, Blue for Completed, Red for Cancelled)
        jTable1.getColumnModel().getColumn(4).setCellRenderer(new DefaultTableCellRenderer() {
            @Override
            public Component getTableCellRendererComponent(JTable table, Object value, boolean isSelected, boolean hasFocus, int row, int column) {
                JLabel label = (JLabel) super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);
                label.setHorizontalAlignment(SwingConstants.CENTER);
                label.setFont(new Font("Segoe UI", Font.BOLD, 12));
                label.setOpaque(true);

                String status = value != null ? value.toString() : "";
                if ("Confirmed".equalsIgnoreCase(status)) {
                    label.setBackground(new java.awt.Color(220, 252, 231));
                    label.setForeground(new java.awt.Color(21, 128, 61));
                } else if ("Pending".equalsIgnoreCase(status)) {
                    label.setBackground(new java.awt.Color(254, 243, 199));
                    label.setForeground(new java.awt.Color(180, 83, 9));
                } else if ("Completed".equalsIgnoreCase(status)) {
                    label.setBackground(new java.awt.Color(219, 234, 254));
                    label.setForeground(new java.awt.Color(29, 78, 216));
                } else if ("Cancelled".equalsIgnoreCase(status)) {
                    label.setBackground(new java.awt.Color(254, 226, 226));
                    label.setForeground(new java.awt.Color(185, 28, 28));
                } else {
                    label.setBackground(java.awt.Color.WHITE);
                    label.setForeground(java.awt.Color.BLACK);
                }
                return label;
            }
        });

        jScrollPane1.getViewport().setBackground(java.awt.Color.WHITE);
    }

