    private void loadreports(){
        String sql =
        "SELECT 'Total Registered Customers' AS Metric, " +
        "CAST(COUNT(*) AS CHAR) AS Value " +
        "FROM customers " +

        "UNION ALL " +

        "SELECT 'Total Registered Pets', CAST(COUNT(*) AS CHAR) " +
        "FROM pets " +

        "UNION ALL " +

        "SELECT 'Total Active Services', CAST(COUNT(*) AS CHAR) " +
        "FROM services WHERE status = 'Active' " +

        "UNION ALL " +

        "SELECT 'Total Appointments', CAST(COUNT(*) AS CHAR) " +
        "FROM appointments " +

        "UNION ALL " +

        "SELECT 'Today''s Estimated Revenue', " +
        "CAST(COALESCE(SUM(s.price), 0) AS CHAR) " +
        "FROM appointments a " +
        "JOIN services s ON a.service_id = s.service_id " +
        "WHERE DATE(a.appointment_datetime) = CURDATE() " +
        "AND a.status <> 'Cancelled' " +

        "UNION ALL " +

        "SELECT 'Appointment Completion Rate', " +
        "CONCAT(COALESCE(ROUND(100.0 * " +
        "SUM(CASE WHEN status = 'Completed' THEN 1 ELSE 0 END) " +
        "/ NULLIF(COUNT(*), 0), 2), 0), '%') " +
        "FROM appointments WHERE status <> 'Cancelled' " +

        "UNION ALL " +

        "SELECT 'Most Popular Service', " +
        "COALESCE((SELECT s.service_name " +
        "FROM appointments a " +
        "JOIN services s ON a.service_id = s.service_id " +
        "WHERE a.status <> 'Cancelled' " +
        "GROUP BY s.service_id, s.service_name " +
        "ORDER BY COUNT(*) DESC, s.service_name ASC " +
        "LIMIT 1), 'No appointments yet')";

    TableLoader.loadTable(jTable1, sql);
    }
